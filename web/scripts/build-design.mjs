import fs from 'node:fs/promises';
import { createHash } from 'node:crypto';
const check = process.argv.includes('--check');
const tokens = JSON.parse(await fs.readFile('design/tokens.json', 'utf8'));
const screens = JSON.parse(await fs.readFile('design/screens.json', 'utf8'));
const implementation = JSON.parse(await fs.readFile('design/implementation-map.json', 'utf8'));
if (Object.keys(implementation).length !== screens.screens.length)
  throw Error('Incomplete screen coverage inventory');
const coverage = screens.screens.map((screen) => {
  const entry = implementation[screen.id];
  if (!entry) throw Error('Missing implementation record: ' + screen.id);
  return {
    id: screen.id,
    title: screen.title,
    referenceContractClaim: screen.status,
    referenceEndpoint: screen.endpoint,
    ...entry,
  };
});
for (const source of new Set(coverage.map((x) => x.source).filter(Boolean)))
  await fs.access(source);
const counts = {};
for (const screen of coverage) counts[screen.status] = (counts[screen.status] ?? 0) + 1;
const inventory = {
  scope:
    'Five-role client; implementation presence is not live backend verification or exact visual parity.',
  referenceScreens: coverage.length,
  counts,
  screens: coverage,
};
const tokenCss =
  '/* Generated by npm run design:build from design/tokens.json. */\n' +
  Object.entries({ ':root': tokens.light, ":root[data-theme='dark']": tokens.dark })
    .map(
      ([selector, values]) =>
        selector +
        ' {\n' +
        Object.entries(values)
          .map(([k, v]) => `  --${k}: ${v};`)
          .join('\n') +
        '\n}',
    )
    .join('\n') +
  '\n';
const template = await fs.readFile('design/prototype/template.html', 'utf8');
const app = (await fs.readFile('design/prototype/app.js', 'utf8')).replace(
  '__SCREEN_SPECS__',
  JSON.stringify(screens.screens).replaceAll('</', '<\\/'),
);
let fonts = '';
for (const set of ['arabic', 'latin']) {
  const buffer = await fs.readFile(
    `node_modules/@fontsource-variable/vazirmatn/files/vazirmatn-${set}-wght-normal.woff2`,
  );
  fonts += `@font-face{font-family:Vazirmatn;src:url(data:font/woff2;base64,${buffer.toString('base64')}) format('woff2');font-weight:100 900;unicode-range:${set === 'arabic' ? 'U+0600-06FF,U+0750-077F,U+08A0-08FF,U+200C-200F,U+FB50-FDFF,U+FE70-FEFC' : 'U+0000-00FF,U+2000-200B,U+2010-206F'}}\n`;
}
const aliases = {
  blue: 'primary',
  'blue-hover': 'primary-hover',
  ink: 'text',
  muted: 'muted',
  line: 'border',
  soft: 'soft',
  'blue-soft': 'primary-soft',
  green: 'success',
  red: 'danger',
  amber: 'warning',
  canvas: 'bg',
};
const prototypeTokens =
  ':root{' +
  Object.entries(aliases)
    .map(([name, token]) => `--${name}:${tokens.light[token]};`)
    .join('') +
  '}';
const html = template
  .replace('__DESIGN_STYLES__', fonts + (await fs.readFile('design/prototype/styles.css', 'utf8')))
  .replace('__PROTOTYPE_TOKENS__', prototypeTokens)
  .replace('__DESIGN_APP__', app);
for (const [file, content] of [
  ['src/design/tokens.css', tokenCss],
  ['output/design/makan-responsive-prototype.html', html],
  ['docs/quality/SCREEN_COVERAGE.json', JSON.stringify(inventory, null, 2) + '\n'],
]) {
  if (check) {
    if ((await fs.readFile(file, 'utf8').catch(() => null)) !== content)
      throw Error('Generated file is stale: ' + file);
  } else {
    await fs.mkdir(file.slice(0, file.lastIndexOf('/')), { recursive: true });
    await fs.writeFile(file, content);
  }
}
console.log(
  JSON.stringify({
    mode: check ? 'verified' : 'generated',
    screens: screens.screens.length,
    prototypeSha256: createHash('sha256').update(html).digest('hex'),
  }),
);
